-- ============================================================
-- ESQUEMA DE BASE DE DATOS - Sys.Ventas (H2)
-- ============================================================
-- Versión H2 del esquema del sistema de ventas "Sys.Ventas".
-- Tiene la misma estructura lógica que schema_neon.sql, pero con
-- tipos/sintaxis propios de H2 (IDENTITY, DOUBLE, sin CASCADE en DROP).
--
-- ¿Qué hace esta base de datos?
-- - Configura catálogos: perfil, categoria, marca, unid_medida.
-- - Gestiona acceso: usuario con perfil y menú dinámico por perfil.
-- - Gestiona inventario: producto con precio, stock y catálogos.
-- - Gestiona clientes: nombre, DNI/RUC, dirección, teléfono.
-- - Soporta POS: vent_carrito como carrito temporal.
-- - Registra ventas: venta (cabecera/comprobante) y venta_detalle (ítems).
-- - Controla estado de venta: ACTIVO/ANULADO con motivo/fecha/usuario.
-- ============================================================

-- ------------------------------------------------------------
-- LIMPIEZA DE TABLAS
-- ------------------------------------------------------------
-- Elimina tablas existentes para recrear el esquema limpio.
-- Se borran primero las tablas dependientes para evitar errores de FK.
DROP TABLE IF EXISTS venta_detalle; -- Ítems de venta (depende de venta)
DROP TABLE IF EXISTS venta;         -- Cabecera/comprobante de venta
DROP TABLE IF EXISTS vent_carrito;  -- Carrito temporal del POS
DROP TABLE IF EXISTS cliente;       -- Clientes
DROP TABLE IF EXISTS producto;      -- Productos/inventario
DROP TABLE IF EXISTS menu;          -- Menú dinámico por perfil
DROP TABLE IF EXISTS usuario;       -- Usuarios del sistema
DROP TABLE IF EXISTS unid_medida;   -- Unidades de medida
DROP TABLE IF EXISTS marca;         -- Marcas
DROP TABLE IF EXISTS categoria;     -- Categorías
DROP TABLE IF EXISTS perfil;        -- Perfiles/roles

-- ------------------------------------------------------------
-- TABLA: perfil
-- ------------------------------------------------------------
-- Roles del sistema (ADMINISTRADOR, VENDEDOR).
CREATE TABLE perfil (
    id_perfil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(50) NOT NULL                                    -- Nombre del perfil
);

-- ------------------------------------------------------------
-- TABLA: categoria
-- ------------------------------------------------------------
-- Clasificación de productos.
CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(100) NOT NULL                                       -- Nombre de categoría
);

-- ------------------------------------------------------------
-- TABLA: marca
-- ------------------------------------------------------------
-- Marca/fabricante o marca comercial del producto.
CREATE TABLE marca (
    id_marca BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(100) NOT NULL                                   -- Nombre de marca
);

-- ------------------------------------------------------------
-- TABLA: unid_medida
-- ------------------------------------------------------------
-- Unidad en la que se vende/controla el producto.
CREATE TABLE unid_medida (
    id_unid_medida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(100) NOT NULL,                                       -- Nombre (Unidad, Caja...)
    abreviatura VARCHAR(20)                                             -- Abreviatura (UND, CJ...)
);

-- ------------------------------------------------------------
-- TABLA: usuario
-- ------------------------------------------------------------
-- Credenciales y perfil para iniciar sesión.
CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    username VARCHAR(50) NOT NULL UNIQUE,                           -- Usuario único de login
    password VARCHAR(100) NOT NULL,                                 -- Contraseña
    id_perfil BIGINT DEFAULT 1                                      -- Perfil asociado (1 por defecto)
);

-- ------------------------------------------------------------
-- TABLA: menu
-- ------------------------------------------------------------
-- Opciones de menú visibles según perfil.
CREATE TABLE menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    menu_nombre VARCHAR(50) NOT NULL,                       -- Grupo de menú
    menu_item_nombre VARCHAR(50),                           -- Nombre visible de la opción
    id_nombre_obj VARCHAR(50) NOT NULL,                     -- ID interno de vista/acción en la app
    perfil VARCHAR(30) NOT NULL                             -- Perfil al que aplica
);

-- ------------------------------------------------------------
-- TABLA: producto
-- ------------------------------------------------------------
-- Productos del inventario.
CREATE TABLE producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(100) NOT NULL,                           -- Nombre del producto
    precio DOUBLE NOT NULL DEFAULT 0,                       -- Precio unitario
    stock DOUBLE NOT NULL DEFAULT 0,                        -- Stock actual
    id_categoria BIGINT DEFAULT 1,                          -- Referencia a categoría
    id_marca BIGINT DEFAULT 1,                              -- Referencia a marca
    id_unid_medida BIGINT DEFAULT 1                         -- Referencia a unidad de medida
);

-- ------------------------------------------------------------
-- TABLA: cliente
-- ------------------------------------------------------------
-- Clientes del negocio. dni_ruc acepta DNI (8) o RUC (11).
CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    nombre VARCHAR(100) NOT NULL,                                   -- Nombre/razón social
    dni_ruc VARCHAR(20),                                            -- DNI o RUC
    direccion VARCHAR(150),                                         -- Dirección
    telefono VARCHAR(30)                                            -- Teléfono
);

-- ------------------------------------------------------------
-- TABLA: vent_carrito
-- ------------------------------------------------------------
-- Carrito temporal del POS antes de registrar la venta.
CREATE TABLE vent_carrito (
    id_vent_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    id_producto BIGINT NOT NULL,                                         -- Producto agregado
    nombre_producto VARCHAR(150) NOT NULL,                               -- Snapshot del nombre
    cantidad DOUBLE NOT NULL,                                            -- Cantidad
    p_buffer DOUBLE NOT NULL,                                            -- Precio unitario capturado
    subtotal DOUBLE NOT NULL,                                            -- Subtotal del ítem
    id_usuario BIGINT                                                    -- Usuario del POS
);

-- ------------------------------------------------------------
-- TABLA: venta
-- ------------------------------------------------------------
-- Cabecera de venta / comprobante emitido.
CREATE TABLE venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    fecha TIMESTAMP NOT NULL,                                     -- Fecha/hora de venta
    id_cliente BIGINT,                                            -- Cliente asociado
    id_usuario BIGINT,                                            -- Usuario que registró
    total DOUBLE NOT NULL,                                        -- Total de la venta
    tipo_comprobante VARCHAR(30),                                 -- Tipo: BOLETA, etc.
    serie VARCHAR(10),                                            -- Serie del comprobante
    nro_comprobante VARCHAR(30),                                  -- Número del comprobante
    estado VARCHAR(20) DEFAULT 'ACTIVO',                          -- ACTIVO / ANULADO
    motivo_anulacion VARCHAR(255),                                -- Motivo de anulación
    fecha_anulacion TIMESTAMP,                                    -- Fecha de anulación
    usuario_anulacion BIGINT                                      -- Usuario que anuló
);

-- ------------------------------------------------------------
-- TABLA: venta_detalle
-- ------------------------------------------------------------
-- Detalle de productos vendidos en cada venta.
CREATE TABLE venta_detalle (
    id_venta_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID autoincremental
    id_venta BIGINT NOT NULL,                                             -- FK a venta
    id_producto BIGINT NOT NULL,                                          -- Producto vendido
    cantidad DOUBLE NOT NULL,                                             -- Cantidad
    precio DOUBLE NOT NULL,                                               -- Precio unitario
    subtotal DOUBLE NOT NULL,                                             -- Subtotal
    CONSTRAINT fk_venta_detalle_venta FOREIGN KEY (id_venta) REFERENCES venta(id_venta) ON DELETE CASCADE
);

